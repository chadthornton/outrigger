#!/usr/bin/env python3
"""Gzips the pages in web/ into a C header the firmware serves from flash.

usage: embed_web.py OUT_HEADER web/index.html web/setup.html
Each file becomes `static const uint8_t k<Name>HtmlGz[]` (index.html -> kIndexHtmlGz).
mtime is fixed so the output only changes when a page does.
"""
import gzip
import pathlib
import sys


def main() -> None:
    out = pathlib.Path(sys.argv[1])
    parts = ["// Generated by tools/embed_web.py from web/. Don't edit.", "#pragma once", "#include <stdint.h>", ""]
    for src in map(pathlib.Path, sys.argv[2:]):
        data = gzip.compress(src.read_bytes(), compresslevel=9, mtime=0)
        name = "k" + "".join(w.capitalize() for w in src.stem.split("_")) + src.suffix[1:].capitalize() + "Gz"
        body = ",".join(str(b) for b in data)
        parts.append(f"// {src.name}: {src.stat().st_size} bytes, {len(data)} gzipped")
        parts.append(f"static const uint8_t {name}[] = {{{body}}};")
        parts.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts))


if __name__ == "__main__":
    main()
