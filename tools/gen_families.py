"""The loader's family blocks, from the reviewed table and a lineage snapshot.

tools/fm1_families.json is the reviewed table (what each family means, and our
own survey's ids, which override mutant.cloud). tools/fm1_lineage.json is a
committed snapshot of what mutant.cloud and the Firmware Hub say each firmware
is built on. This writes lib/fm1_loader/src/families_gen.h: the projects the
board refuses to install, and why. The board never reads either catalog, so a
listing's edit on mutant.cloud changes nothing until someone refreshes the
snapshot, reviews the header's diff and ships a build.

    python3 -I tools/gen_families.py              # regenerate the header
    python3 -I tools/gen_families.py --check      # exit 1 if it's out of date (make test)
    python3 -I tools/gen_families.py --refresh    # fetch a new lineage snapshot, then regenerate

Standard library only.
"""
import argparse
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FAMILIES = ROOT / "tools/fm1_families.json"
LINEAGE = ROOT / "tools/fm1_lineage.json"
HEADER = ROOT / "lib/fm1_loader/src/families_gen.h"
UA = "outrigger-gen-families (+https://github.com/chadthornton/outrigger)"
SOURCES = {
    "firmware": "https://mutant.cloud/firmware.json?device=fm1&kind=firmware",
    "catalog": "https://mutant.cloud/catalog.json?device=fm1",
    "hub": "https://thefirmwarehub.com/catalog.json",
}
BLOCKS = ("bluetooth", "old-felucca")


def load(path):
    return json.loads(Path(path).read_text())


def category(entry_id, bases, fam):
    """bluetooth, old-felucca, keep, clean or unknown for a firmware, following
    "built on" through firmwares that are bases themselves (Tribe -> X0X -> Felucca).
    bases: {entry id: [base, ...]}. Our survey's ids win over what the catalogs say."""
    if entry_id in fam["blocked_ids"]:
        return fam["blocked_ids"][entry_id]
    if entry_id == "stock" or entry_id in fam["keep"]:
        return "keep"
    seen, todo, found = {entry_id}, list(bases.get(entry_id) or []), set()
    while todo:
        b = todo.pop()
        if b in fam["blocked_ids"]:
            return fam["blocked_ids"][b]
        if b in fam["blocked_bases"]:
            return fam["blocked_bases"][b]
        if b in fam["keep"] or b == "stock":
            found.add("keep")
        elif b in fam["clean"]:
            found.add("clean")
        elif b not in seen and b in bases:
            seen.add(b)
            todo += bases[b] or []
    return "keep" if found == {"keep"} else "clean" if found else "unknown"


def lineage_bases(lineage):
    """{id: [base, ...]} from both catalogs: a block from either one counts."""
    out = {}
    for i, b in lineage["mutant"].items():
        out.setdefault(i, []).extend([b] if b else [])
    for i, bs in lineage["hub"].items():
        out.setdefault(i, []).extend(bs)
    return out


def blocked_projects(fam, lineage):
    """{project: reason} for every project id a firmware can reach the board under:
    the catalogs' ids and mutant.cloud's per-file row ids of a blocked firmware."""
    bases = lineage_bases(lineage)
    out = {i: fam["blocked_ids"][i] for i in fam["blocked_ids"]}
    for i in bases:
        c = category(i, bases, fam)
        if c in BLOCKS:
            out[i] = c
    for row, entry in lineage["variants"].items():
        if entry in out:
            out[row] = out[entry]
    return dict(sorted(out.items()))


def header(blocked):
    lines = [
        "// Generated by tools/gen_families.py from tools/fm1_families.json and",
        "// tools/fm1_lineage.json: don't edit. The projects the loader refuses to",
        "// install, by why (library.cpp blocked_reason).",
        "#pragma once",
        "",
        "namespace fm1_loader {",
        "namespace families {",
        "",
    ]
    for reason, name in (("bluetooth", "kBlockedBluetooth"), ("old-felucca", "kBlockedOldFelucca")):
        ids = [p for p, r in blocked.items() if r == reason]
        lines.append(f"// {len(ids)} projects.")
        lines.append(f"constexpr const char *{name}[] = {{")
        lines += [f'    "{p}",' for p in ids]
        lines += ["};", ""]
    lines += ["}  // namespace families", "}  // namespace fm1_loader", ""]
    return "\n".join(lines)


def refresh():
    def get(url):
        req = urllib.request.Request(url, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.loads(r.read())
    fw, cat, hub = (get(SOURCES[k]) for k in ("firmware", "catalog", "hub"))
    lineage = {
        "about": "A snapshot of what each FM-1 firmware is built on, from " + ", ".join(SOURCES.values())
                 + ". Refreshed by tools/gen_families.py --refresh; review the header's diff.",
        "mutant": {e["id"]: e.get("base") for e in fw["entries"]},
        "variants": {e["id"]: e["entry"] for e in cat["firmwares"] if e.get("entry") and e["id"] != e["entry"]},
        "hub": {e["id"]: e.get("base") or [] for e in hub["firmwares"]},
    }
    for k in ("mutant", "variants", "hub"):
        lineage[k] = dict(sorted(lineage[k].items()))
    LINEAGE.write_text(json.dumps(lineage, indent=1) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--refresh", action="store_true")
    args = ap.parse_args(argv)
    if args.refresh:
        refresh()
    text = header(blocked_projects(load(FAMILIES), load(LINEAGE)))
    if args.check:
        if HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run python3 -I tools/gen_families.py", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
