// bench_main.c: the Vibe bench on Big-P4. Two Vibes built with the VIBE FM SDK (example-synth and the Faust patch),
// each run three ways: the .wasm in WAMR's interpreter (classic or fast, per image), the .aot (wamrc, riscv32
// ilp32f), and the same C compiled natively. Console on UART0 (UART-C), A1's command style: one letter, no Enter.
//   i  info        B  the sweep: 2 Vibes x interp/aot/native x 1, 4, 8 notes, one VIBE line each, then "BENCH sweep done"
//   s  example-synth only     f  faust-synth only     b  block 128 <-> 64 frames     m  memory
// Boot prints "BENCH ready: ...", then "BENCH alive" every 10 s.
#include <stdio.h>
#include <string.h>
#include <math.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "freertos/queue.h"
#include "driver/uart.h"
#include "driver/uart_vfs.h"
#include "esp_cpu.h"
#include "esp_clk_tree.h"
#include "esp_chip_info.h"
#include "esp_mac.h"
#include "esp_heap_caps.h"
#include "esp_timer.h"
#include <pthread.h>
#include "esp_pthread.h"
#include "vh.h"
#include "vh_expect.h"   // generated by tools/build_p4.sh: the hashes the Mac and wasmtest.mjs measured

extern const uint8_t es_wasm_start[] asm("_binary_example_synth_wasm_start");
extern const uint8_t es_wasm_end[] asm("_binary_example_synth_wasm_end");
extern const uint8_t fs_wasm_start[] asm("_binary_faust_synth_wasm_start");
extern const uint8_t fs_wasm_end[] asm("_binary_faust_synth_wasm_end");
extern const uint8_t es_aot_start[] asm("_binary_example_synth_aot_start");
extern const uint8_t es_aot_end[] asm("_binary_example_synth_aot_end");
extern const uint8_t fs_aot_start[] asm("_binary_faust_synth_aot_start");
extern const uint8_t fs_aot_end[] asm("_binary_faust_synth_aot_end");

typedef struct {
  const char *name;
  const uint8_t *wasm, *wasm_end, *aot, *aot_end;
  void (*native)(vh_backend *);
  const uint32_t *expect;   // out_hash at 1, 4, 8 notes (128-frame blocks, 48 kHz)
  const uint32_t *expect64; // the same with 64-frame blocks
  int native_runs;          // native state isn't reset between runs: only the first one after boot is fresh
} vibe_fw;

static const uint32_t es_expect[3] = { VH_EXPECT_ES_1, VH_EXPECT_ES_4, VH_EXPECT_ES_8 };
static const uint32_t fs_expect[3] = { VH_EXPECT_FS_1, VH_EXPECT_FS_4, VH_EXPECT_FS_8 };
static const uint32_t es_expect64[3] = { VH_EXPECT64_ES_1, VH_EXPECT64_ES_4, VH_EXPECT64_ES_8 };
static const uint32_t fs_expect64[3] = { VH_EXPECT64_FS_1, VH_EXPECT64_FS_4, VH_EXPECT64_FS_8 };
static vibe_fw FW[2] = {
  { "example-synth", es_wasm_start, es_wasm_end, es_aot_start, es_aot_end, vh_native_vibe_synth, es_expect, es_expect64, 0 },
  { "faust-synth", fs_wasm_start, fs_wasm_end, fs_aot_start, fs_aot_end, vh_native_faust_synth, fs_expect, fs_expect64, 0 },
};
static int g_block = 128;
static uint32_t g_cpu_hz = 400000000;
static QueueHandle_t g_cmd;

// ---- a 64-bit cycle clock (the 32-bit counter wraps every 10.7 s at 400 MHz); no division inside the timed span --
static uint64_t clock_cycles(void)
{
  static uint32_t last, hi;
  uint32_t c = esp_cpu_get_cycle_count();
  if (c < last) hi++;
  last = c;
  return ((uint64_t)hi << 32) | c;
}

static void log_out(const char *s, int n) { printf("VIBE log: %.*s\n", n, s); }

static void info(void)
{
  uint8_t mac[6];
  esp_efuse_mac_get_default(mac);
  esp_chip_info_t ci;
  esp_chip_info(&ci);
  printf("BENCH P4 vibe bench, MAC %02x:%02x:%02x:%02x:%02x:%02x, cpu %lu MHz, chip rev %u, wamr %s, native bss %s, "
         "heap internal %u, psram %u free of %u\n",
         mac[0], mac[1], mac[2], mac[3], mac[4], mac[5], (unsigned long)(g_cpu_hz / 1000000), (unsigned)ci.revision,
         vh_wamr_mode(), VH_NATIVE_BSS, (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL),
         (unsigned)heap_caps_get_free_size(MALLOC_CAP_SPIRAM), (unsigned)heap_caps_get_total_size(MALLOC_CAP_SPIRAM));
  for (int i = 0; i < 2; i++)
    printf("BENCH module %s wasm %u B, aot %u B, expect %08lx %08lx %08lx\n", FW[i].name,
           (unsigned)(FW[i].wasm_end - FW[i].wasm), (unsigned)(FW[i].aot_end - FW[i].aot),
           (unsigned long)FW[i].expect[0], (unsigned long)FW[i].expect[1], (unsigned long)FW[i].expect[2]);
}

static void memory(const char *when)
{
  printf("BENCH memory %s: internal free %u (min %u), psram free %u (min %u)\n", when,
         (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL), (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL),
         (unsigned)heap_caps_get_free_size(MALLOC_CAP_SPIRAM), (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_SPIRAM));
}

// reference render (the interpreter's) for the AOT and native comparisons
static float *ref_l, *ref_r, *cur_l, *cur_r;
static size_t frames_max;

static void diff(const float *al, const float *bl, size_t n, double *maxabs, double *db)
{
  double sd = 0, sa = 0, mx = 0;
  for (size_t i = 0; i < n; i++) { double d = fabs((double)al[i] - bl[i]); if (d > mx) mx = d; sd += d * d; sa += (double)al[i] * al[i]; }
  *maxabs = mx;
  *db = (sd > 0 && sa > 0) ? 10.0 * log10(sd / sa) : -999.0;
}

static void row(vibe_fw *fw, vh_backend *b, int notes, const char *kind, int64_t load_us)
{
  vh_scenario s = { notes, 48000.0f, g_block, 2.5f, 1.5f, (double)g_cpu_hz / 1e6 };
  vh_result r;
  const size_t in0 = heap_caps_get_free_size(MALLOC_CAP_INTERNAL), ps0 = heap_caps_get_free_size(MALLOC_CAP_SPIRAM);
  const int64_t t0 = esp_timer_get_time();
  float *ol = strcmp(kind, "interp") == 0 ? ref_l : cur_l, *orr = strcmp(kind, "interp") == 0 ? ref_r : cur_r;
  int rc = vh_run(b, &s, clock_cycles, &r, ol, orr);
  const int64_t t1 = esp_timer_get_time();
  if (rc) { printf("VIBE fw=%s be=%s notes=%d FAILED rc=%d err=\"%s\"\n", fw->name, b->name, notes, rc, b->err); return; }
  const int ni = notes == 1 ? 0 : notes == 4 ? 1 : 2;
  const uint32_t want = g_block == 128 ? fw->expect[ni] : g_block == 64 ? fw->expect64[ni] : 0;
  const double budget = (double)g_block * 1e6 / 48000.0;
  char cmp[96] = "";
  if (strcmp(kind, "interp") != 0) {
    double mx, db;
    diff(ref_l, ol, (size_t)r.blocks * g_block, &mx, &db);
    snprintf(cmp, sizeof cmp, " vs_interp_max=%.3g vs_interp_db=%.1f", mx, db);
  }
  const char *match = strcmp(kind, "native") == 0 || !want ? "n/a" : (r.out_hash == want ? "yes" : "NO");
  printf("VIBE fw=%s be=%s notes=%d block=%d hash=%08lx expect=%08lx match=%s peak=%.3f rms=%.4f nan=%lu "
         "us_mean=%.1f us_held=%.1f us_max=%.1f max_block=%lu budget_us=%.0f held_pct=%.1f load_us=%lld run_ms=%lld "
         "internal_used=%d psram_used=%d%s%s\n",
         fw->name, b->name, notes, g_block, (unsigned long)r.out_hash, (unsigned long)want, match, r.peak, r.rms,
         (unsigned long)r.nan, r.us_mean, r.us_mean_held, r.us_max, (unsigned long)r.us_max_block, budget,
         100.0 * r.us_mean_held / budget, (long long)load_us, (long long)((t1 - t0) / 1000),
         (int)(in0 - heap_caps_get_free_size(MALLOC_CAP_INTERNAL)), (int)(ps0 - heap_caps_get_free_size(MALLOC_CAP_SPIRAM)),
         cmp, strcmp(kind, "native") == 0 ? (fw->native_runs == 1 ? " fresh=1" : " fresh=0") : "");
}

static void run_fw(vibe_fw *fw)
{
  static const int notes[3] = { 1, 4, 8 };
  for (int k = 0; k < 3; k++) {
    // 1. the .wasm in the interpreter (the reference for the other two)
    vh_backend b;
    int64_t t0 = esp_timer_get_time();
    if (vh_wamr_open(&b, fw->wasm, (uint32_t)(fw->wasm_end - fw->wasm), 0, 32 * 1024, log_out)) {
      printf("VIBE fw=%s be=wasm FAILED \"%s\"\n", fw->name, b.err);
      if (b.fini) b.fini(&b);
    } else {
      row(fw, &b, notes[k], "interp", esp_timer_get_time() - t0);
      b.fini(&b);
    }
    // 2. the .aot
    if (fw->aot_end - fw->aot < 16) printf("VIBE fw=%s be=wamr-aot MISSING (no .aot in this image)\n", fw->name);
    else {
      t0 = esp_timer_get_time();
      if (vh_wamr_open(&b, fw->aot, (uint32_t)(fw->aot_end - fw->aot), 0, 32 * 1024, log_out)) {
        printf("VIBE fw=%s be=wamr-aot FAILED \"%s\"\n", fw->name, b.err);
        if (b.fini) b.fini(&b);
      } else {
        row(fw, &b, notes[k], "aot", esp_timer_get_time() - t0);
        b.fini(&b);
      }
    }
    // 3. native
    fw->native(&b);
    fw->native_runs++;
    row(fw, &b, notes[k], "native", 0);
    b.fini(&b);
  }
}

// a pthread, not a bare FreeRTOS task: WAMR's ESP-IDF port calls pthread_self(), which asserts on a task that
// pthread_create didn't start (espidf_thread.c, os_self_thread). Runtime init and every run stay on this thread.
static void *bench_task(void *arg)
{
  (void)arg;
  if (vh_wamr_runtime_init(0, 0)) printf("BENCH wamr init FAILED\n");
  vh_native_log = log_out;
  frames_max = (size_t)((2.5 * 48000 + 63) / 64) * 64 + 256;
  ref_l = heap_caps_malloc(frames_max * 4, MALLOC_CAP_SPIRAM); ref_r = heap_caps_malloc(frames_max * 4, MALLOC_CAP_SPIRAM);
  cur_l = heap_caps_malloc(frames_max * 4, MALLOC_CAP_SPIRAM); cur_r = heap_caps_malloc(frames_max * 4, MALLOC_CAP_SPIRAM);
  if (!ref_l || !ref_r || !cur_l || !cur_r) printf("BENCH output buffers FAILED\n");
  for (;;) {
    char c;
    if (xQueueReceive(g_cmd, &c, portMAX_DELAY) != pdTRUE) continue;
    switch (c) {
      case 'B':
        printf("BENCH sweep: 2 Vibes x interp/aot/native x 1, 4, 8 notes, block %d, wamr %s\n", g_block, vh_wamr_mode());
        memory("before");
        run_fw(&FW[0]); run_fw(&FW[1]);
        memory("after");
        printf("BENCH sweep done\n");
        break;
      case 's': run_fw(&FW[0]); printf("BENCH example-synth done\n"); break;
      case 'f': run_fw(&FW[1]); printf("BENCH faust-synth done\n"); break;
      default: break;
    }
  }
  return NULL;
}

void app_main(void)
{
  esp_clk_tree_src_get_freq_hz(SOC_MOD_CLK_CPU, ESP_CLK_TREE_SRC_FREQ_PRECISION_EXACT, &g_cpu_hz);
  uart_driver_install(UART_NUM_0, 512, 0, 0, NULL, 0);
  uart_vfs_dev_use_driver(UART_NUM_0);
  setvbuf(stdout, NULL, _IONBF, 0);
  vTaskDelay(pdMS_TO_TICKS(1500));   // time for the Mac to open the port (opening it resets the board)
  info();
  memory("boot");
  g_cmd = xQueueCreate(16, 1);
  esp_pthread_cfg_t pc = esp_pthread_get_default_config();
  pc.stack_size = 32 * 1024; pc.prio = 10; pc.pin_to_core = 1; pc.thread_name = "vibe";
  esp_pthread_set_cfg(&pc);
  pthread_t th;
  if (pthread_create(&th, NULL, bench_task, NULL) != 0) printf("BENCH bench thread FAILED\n");
  printf("BENCH ready: i info, B sweep, s example-synth, f faust-synth, b block 128/64, m memory\n");
  int64_t last = esp_timer_get_time();
  for (;;) {
    uint8_t c;
    if (uart_read_bytes(UART_NUM_0, &c, 1, pdMS_TO_TICKS(100)) == 1) {
      switch (c) {
        case 'i': info(); break;
        case 'm': memory("now"); break;
        case 'b': g_block = g_block == 128 ? 64 : 128; printf("BENCH block %d frames (budget %.0f us)\n", g_block, g_block * 1e6 / 48000.0); break;
        case 'B': case 's': case 'f': { char k = (char)c; xQueueSend(g_cmd, &k, 0); break; }
        default: break;
      }
    }
    if (esp_timer_get_time() - last >= 10000000) { last = esp_timer_get_time(); printf("BENCH alive\n"); }
  }
}
