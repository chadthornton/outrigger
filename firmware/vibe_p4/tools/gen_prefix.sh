#!/bin/sh
# gen_prefix.sh PREFIX OUT.h SRC.c... : a header of #defines that renames every global a Vibe and its copy of the SDK
# define, so two natively compiled Vibes link into one image. Compiled with the host's clang; the native build on the P4
# defines the same globals (same sources, same macros: no __wasm__).
set -e
P="$1"; OUT="$2"; shift 2
INC="-I${VIBE_SDK:?set VIBE_SDK}/sdk/include -I$VIBE_SDK/sdk/src"
T=$(mktemp -d)
for f in "$@"; do clang -O2 $INC $VH_PREFIX_CFLAGS -w -c -o "$T/$(basename "$f" .c).o" "$f"; done
{
  echo "/* generated by tools/gen_prefix.sh $P: do not edit */"
  echo "#pragma once"
  nm -g --defined-only "$T"/*.o | awk 'NF==3 {print $3}' | sed 's/^_//' | grep -v '^vibe_host_' | sort -u | while read s; do echo "#define $s ${P}$s"; done
} > "$OUT"
rm -rf "$T"
echo "wrote $OUT ($(grep -c '#define' "$OUT") symbols)"
