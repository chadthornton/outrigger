#!/bin/sh
# build_p4.sh: everything from the pinned sources to the two flashable Big-P4 images.
#
#   firmware/vibe_p4/tools/build_p4.sh            # fetch (once), build the Vibes, check them on the Mac, build both images
#
# Sources live outside the repo, in $S (default ~/Projects/spike-ext/s1):
#   vibe-fm-sdk  github.com/Vibe-FM-SDK/vibe-fm-sdk @ 2ac2340 (SDK 27, Apache-2.0)
#   wamr         github.com/bytecodealliance/wasm-micro-runtime @ WAMR-2.4.4, plus p4/wamr-2.4.4-p4.patch
#   wamrc        built from that WAMR (wamr-compiler/, LLVM 18 via build_llvm.py; 4 min 7 s measured, plus the clone, once)
# Tools: zig (the SDK asks for 0.13.0; 0.15.2 measured fine), node (wasmtest.mjs), faust 2.88.0 only to regenerate
# faust_voice.h, cmake + ninja, ESP-IDF v5.5.5 in ~/.espressif (pyenv 3.13.3 for its Python).
#
# Out, outside the repo, in $OUT (default $S/p4img):
#   $OUT/fast/vibe_bench_p4.merged.bin      image (b): WAMR fast interpreter + AOT + native      -> write at 0x0
#   $OUT/classic/vibe_bench_p4.merged.bin   image (a): WAMR classic interpreter + AOT + native   -> write at 0x0
#   $OUT/fast-int/vibe_bench_p4.merged.bin  image (b) with the native Vibes' state in internal SRAM -> write at 0x0
#   $OUT/modules/                           the embedded .wasm/.aot and vh_expect.h
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
S="${S:-$HOME/Projects/spike-ext/s1}"
OUT="${OUT:-$S/p4img}"
case "$OUT" in "$(git -C "$here" rev-parse --show-toplevel)"*) echo "OUT is inside the repo" >&2; exit 1;; esac
SDK="$S/vibe-fm-sdk"; WAMR="$S/wamr"; WAMRC="$WAMR/wamr-compiler/build/wamrc"
mkdir -p "$S" "$OUT/modules"

# ---- 1. sources, pinned ------------------------------------------------------------------------------------------------
[ -d "$SDK" ] || git clone https://github.com/Vibe-FM-SDK/vibe-fm-sdk.git "$SDK"
git -C "$SDK" checkout -q 2ac2340
[ -d "$WAMR" ] || git clone --depth 1 --branch WAMR-2.4.4 https://github.com/bytecodealliance/wasm-micro-runtime.git "$WAMR"
if git -C "$WAMR" apply --check "$here/p4/wamr-2.4.4-p4.patch" 2>/dev/null; then
  git -C "$WAMR" apply "$here/p4/wamr-2.4.4-p4.patch"; echo "applied the P4 patch to WAMR"
fi
if [ ! -x "$WAMRC" ]; then
  (cd "$WAMR/wamr-compiler" && uv run --with requests==2.32.4 python ../build-scripts/build_llvm.py --platform darwin \
     --arch AArch64 RISCV "--extra-cmake-flags=-DLLVM_CCACHE_BUILD=OFF" \
   && mkdir -p build && cd build && cmake .. -G Ninja -DWAMR_BUILD_PLATFORM=darwin && ninja)
fi

# ---- 2. the Vibes, with the SDK's own build script --------------------------------------------------------------------
(cd "$SDK" && sh tools/build.sh examples/example-synth && sh tools/build.sh "$here/faust-synth")
cp "$SDK/build/example-synth.wasm" "$SDK/build/faust-synth.wasm" "$OUT/modules/"
for fw in example-synth faust-synth; do   # riscv32, the P4's ISA (rv32imafc, hard single float), software bounds checks
  "$WAMRC" --target=riscv32 --target-abi=ilp32f --cpu=generic-rv32 --cpu-features=+m,+a,+c,+f --bounds-checks=1 \
    -o "$OUT/modules/$fw.aot" "$OUT/modules/$fw.wasm"
done

# ---- 3. the Mac check: the SDK's Node host is the reference; our shim must match it bit for bit -------------------
B="$S/build/mac-fast"
cmake -S "$here/mac" -B "$B" -G Ninja -DVIBE_SDK="$SDK" -DWAMR_ROOT="$WAMR" -DVH_FAUST=1 >/dev/null && ninja -C "$B" >/dev/null
{
  echo "/* generated by tools/build_p4.sh: wasmtest.mjs out_hash, 48 kHz, 128-frame blocks, the fixed scenario */"
  echo "#pragma once"
} > "$OUT/modules/vh_expect.h"
for fw in example-synth faust-synth; do
  tag=$([ $fw = example-synth ] && echo ES || echo FS)
  for n in 1 4 8; do
    d="$S/wt-$fw-$n"; mkdir -p "$d"
    ref=$(cd "$SDK" && node tools/wasmtest.mjs "build/$fw.wasm" "$here/scripts/notes$n.json" "$d" | sed -n 's/.*"out_hash":"\([0-9a-f]*\)".*/\1/p')
    got=$("$B/vibe_run" wamr "$OUT/modules/$fw.wasm" --notes "$n" 2>/dev/null | sed -n 's/.*"out_hash":"\([0-9a-f]*\)".*/\1/p')
    echo "$fw $n notes: wasmtest.mjs $ref, WAMR shim $got"
    [ -n "$ref" ] && [ "$ref" = "$got" ] || { echo "MISMATCH: the shim doesn't reproduce the SDK's host" >&2; exit 1; }
    echo "#define VH_EXPECT_${tag}_$n 0x$ref" >> "$OUT/modules/vh_expect.h"
    # 64-frame blocks: wasmtest.mjs only does 128, so the reference is the shim (classic = fast = wasmtest at 128)
    h64=$("$B/vibe_run" wamr "$OUT/modules/$fw.wasm" --notes "$n" --block 64 2>/dev/null | sed -n 's/.*"out_hash":"\([0-9a-f]*\)".*/\1/p')
    echo "#define VH_EXPECT64_${tag}_$n 0x$h64" >> "$OUT/modules/vh_expect.h"
  done
done

# ---- 4. the native Vibes' symbol prefixes (two copies of the SDK in one image) -------------------------------------
VIBE_SDK="$SDK" "$here/tools/gen_prefix.sh" vs_ "$here/gen/prefix_vs.h" "$SDK/examples/example-synth/synth.c" \
  "$SDK/sdk/src/vibe_sdk.c" "$SDK/sdk/src/vibe_font.c"
VIBE_SDK="$SDK" VH_PREFIX_CFLAGS="-I$here/faust-synth" "$here/tools/gen_prefix.sh" fs_ "$here/gen/prefix_fs.h" \
  "$here/faust-synth/faust_synth.c" "$here/faust-synth/fm_math.c" "$SDK/sdk/src/vibe_sdk.c" "$SDK/sdk/src/vibe_font.c"

# ---- 5. the two images ------------------------------------------------------------------------------------------------
# (export.sh refuses to run without gdb and openocd, which a build doesn't need: set the environment it would set)
E="$HOME/.espressif"
export IDF_PATH="$E/esp-idf/v5.5.5" IDF_PYTHON_ENV_PATH="$E/python_env/idf5.5_py3.13_env" ESP_ROM_ELF_DIR="$E/tools/esp-rom-elfs/20241011/"
export PATH="$E/tools/riscv32-esp-elf/esp-14.2.0_20260121/riscv32-esp-elf/bin:$E/tools/cmake/3.30.2/CMake.app/Contents/bin:$E/tools/ninja/1.12.1:$IDF_PYTHON_ENV_PATH/bin:$IDF_PATH/tools:$PATH"
idf() { "$IDF_PYTHON_ENV_PATH/bin/python" "$IDF_PATH/tools/idf.py" "$@"; }
# fast-int: image (b) with the native Vibes' state in internal SRAM instead of PSRAM (the .wasm's memory stays in PSRAM)
for img in fast classic fast-int; do
  bd="$OUT/$img"; mkdir -p "$bd"
  mode=${img%-int}; np=$([ "$img" = fast-int ] && echo 0 || echo 1)
  idf -C "$here/p4" -B "$bd" -DSDKCONFIG="$bd/sdkconfig" -DSDKCONFIG_DEFAULTS="sdkconfig.defaults;sdkconfig.$mode" \
    -DVIBE_SDK="$SDK" -DWAMR_PATH="$WAMR" -DVH_MODULES="$OUT/modules" -DVH_NATIVE_PSRAM=$np build
  idf -C "$here/p4" -B "$bd" -DSDKCONFIG="$bd/sdkconfig" merge-bin -o vibe_bench_p4.merged.bin
  ls -l "$bd/vibe_bench_p4.merged.bin" "$bd/vibe_bench_p4.bin"
done
shasum -a 256 "$OUT"/*/vibe_bench_p4.merged.bin
